"""
Generate Demetrios code for DDI prediction with type-safe units.
"""
function generate_demetrios_ddi(
    perpetrator::String,
    victim::String,
    mechanism::Symbol,
    Ki_uM::Float64,
    fm::Float64;
    kinact_h::Float64 = 0.0,
    KI_uM::Float64 = 0.0
)::String

    mech_str = if mechanism == :reversible
        "Reversible competitive inhibition"
    elseif mechanism == :mbi
        "Mechanism-based inactivation"
    elseif mechanism == :induction
        "Enzyme induction"
    else
        "Mixed mechanism"
    end

    return """
// =============================================================================
// DDI PREDICTION: $(uppercase(perpetrator)) + $(uppercase(victim))
// =============================================================================
// Mechanism: $(mech_str)
// Generated by Darwin PBPK Platform
//
// UNIT SAFETY: All parameters are type-checked at compile time
// =============================================================================

import darwin.ddi.{predict_auc_ratio, DDIMechanism}

/// DDI parameters with compile-time unit verification
struct DDIParams {
    Ki: uM,                    // Inhibition constant
    fm: Fraction,              // Fraction metabolized (0-1)
    $(mechanism == :mbi ? "kinact: per_h,             // MBI inactivation rate\n    KI: uM,                    // MBI concentration for half-max" : "")
}

/// Calculate AUC ratio with type-safe units
/// Compile error if units don't match!
fn calculate_auc_ratio(
    I: uM,                     // Inhibitor concentration (unbound)
    params: &DDIParams
) -> Real {
    $(if mechanism == :reversible
        """
    // Reversible inhibition: R = 1 + [I]/Ki
    let R: Real = 1.0 + I / params.Ki

    // AUC ratio = 1 / (fm/R + (1-fm))
    1.0 / (params.fm / R + (1.0 - params.fm))"""
    elseif mechanism == :mbi
        """
    // MBI: λ = kinact × [I] / (KI + [I])
    let lambda: per_h = params.kinact * I / (params.KI + I)

    // Steady-state enzyme fraction
    let kdeg: per_h = 0.019  // CYP3A4 degradation rate
    let E_ss: Fraction = kdeg / (kdeg + lambda)

    // AUC ratio = 1 / (fm × E_ss + (1-fm))
    1.0 / (params.fm * E_ss + (1.0 - params.fm))"""
    else
        "1.0  // Unknown mechanism"
    end)
}

/// Example usage
fn main() -> effect[IO] {
    let params = DDIParams {
        Ki: $(Ki_uM),        // µM
        fm: $(fm),           // fraction
        $(mechanism == :mbi ? "kinact: $(kinact_h),     // h⁻¹\n        KI: $(KI_uM),          // µM" : "")
    }

    // Clinical concentration (unbound)
    let I_clinical: uM = 10.0

    let auc_ratio = calculate_auc_ratio(I_clinical, &params)

    println!("$(perpetrator) + $(victim)")
    println!("Predicted AUC ratio: {auc_ratio:.1}x")

    // TYPE SAFETY DEMONSTRATION:
    // The following would cause a COMPILE ERROR:
    // let wrong: ng_per_mL = I_clinical  // Error! uM != ng_per_mL
    // let wrong_ratio = calculate_auc_ratio(10.0, &params)  // Error! Real != uM
}
"""
end

"""
Generate Demetrios code for a complete PBPK model with DDI.
"""
function generate_demetrios_pbpk(
    drug_name::String;
    MW::Float64 = 300.0,
    ka::Float64 = 1.0,
    F::Float64 = 0.5,
    Vc::Float64 = 30.0,
    Vp::Float64 = 50.0,
    CL::Float64 = 10.0,
    Q::Float64 = 20.0
)::String

    return """
// =============================================================================
// PBPK MODEL: $(uppercase(drug_name))
// =============================================================================
// Two-compartment oral PK model with first-pass metabolism
// Generated by Darwin PBPK Platform
//
// COMPILE-TIME UNIT SAFETY:
// - All parameters have explicit unit types
// - Unit conversions are verified at compile time
// - Prevents common PBPK bugs (e.g., mL/min vs L/h confusion)
// =============================================================================

import std.math.{exp, log}
import std.effects.{Mut, IO}
import darwin.ode.{solve, Tsit5, ODEProblem}

// =============================================================================
// UNIT TYPE DEFINITIONS
// =============================================================================

type mg = Mass<mg>
type kg = Mass<kg>
type L = Volume<L>
type h = Time<h>
type uM = Amount<umol> / Volume<L>
type L_per_h = Volume<L> / Time<h>
type per_h = 1 / Time<h>
type Fraction = Real { 0.0 <= self <= 1.0 }

// =============================================================================
// MODEL PARAMETERS
// =============================================================================

/// Drug-specific parameters with compile-time unit verification
struct DrugParams {
    name: String,
    MW: Real,                  // g/mol (molecular weight)
    ka: per_h,                 // Absorption rate constant
    F: Fraction,               // Bioavailability
    Fg: Fraction,              // Gut bioavailability
    Fh: Fraction,              // Hepatic bioavailability
    Vc: L,                     // Central volume
    Vp: L,                     // Peripheral volume
    CL: L_per_h,               // Total clearance
    Q: L_per_h,                // Intercompartmental clearance
}

/// Patient-specific parameters
struct PatientParams {
    weight: kg,
    age: Real,                 // years
    sex: String,
    GFR: L_per_h,              // Glomerular filtration rate
}

// =============================================================================
// STATE VARIABLES
// =============================================================================

/// PK state with explicit units
struct PKState {
    A_gut: mg,                 // Amount in gut lumen
    C_central: uM,             // Central concentration
    A_periph: mg,              // Amount in peripheral
    t: h,                      // Current time
}

impl PKState {
    fn new() -> Self {
        PKState {
            A_gut: 0.0,
            C_central: 0.0,
            A_periph: 0.0,
            t: 0.0,
        }
    }
}

// =============================================================================
// ODE SYSTEM
// =============================================================================

/// Two-compartment oral PK model
/// All unit conversions verified at compile time!
fn pk_ode(
    state: &PKState,
    params: &DrugParams
) -> effect[Mut] PKDerivatives {

    // Gut compartment: dA_gut/dt = -ka × A_gut
    let dA_gut: mg_per_h = -params.ka * state.A_gut

    // Absorption rate (amount per time)
    let absorption: mg_per_h = params.ka * state.A_gut * params.F

    // Convert absorption to concentration change
    // dC/dt = (absorption/MW/Vc) - (CL/Vc)×C - (Q/Vc)×(C - Cp)
    let C_periph: uM = (state.A_periph / params.MW) / params.Vp * 1000.0

    let dC_central: uM_per_h = (
        absorption / params.MW / params.Vc * 1000.0  // Absorption
        - params.CL / params.Vc * state.C_central     // Elimination
        - params.Q / params.Vc * (state.C_central - C_periph)  // Distribution
    )

    // Peripheral compartment
    let dA_periph: mg_per_h = params.Q * (state.C_central - C_periph) * params.Vc * params.MW / 1000.0

    PKDerivatives {
        dA_gut,
        dC_central,
        dA_periph,
    }
}

// =============================================================================
// SIMULATION FUNCTION
// =============================================================================

/// Simulate PK profile
/// Returns vector of (time, concentration) pairs
fn simulate(
    params: DrugParams,
    dose: mg,
    t_max: h,
    dt: h
) -> effect[IO, Mut] Vec<(h, uM)> {

    // Initialize state
    var state = PKState::new()
    state.A_gut = dose  // Oral dose

    // Results storage
    var results: Vec<(h, uM)> = Vec::new()

    // Integration loop
    while state.t <= t_max {
        // Store current state
        results.push((state.t, state.C_central))

        // Calculate derivatives
        let derivs = pk_ode(&state, &params)

        // Euler step (use Tsit5 for production)
        state.A_gut += derivs.dA_gut * dt
        state.C_central += derivs.dC_central * dt
        state.A_periph += derivs.dA_periph * dt
        state.t += dt

        // Ensure non-negative
        state.A_gut = max(state.A_gut, 0.0)
        state.C_central = max(state.C_central, 0.0)
        state.A_periph = max(state.A_periph, 0.0)
    }

    results
}

// =============================================================================
// PK METRICS CALCULATION
// =============================================================================

/// Calculate AUC using trapezoidal rule
/// Note: Input and output types are explicit
fn calculate_auc(profile: &Vec<(h, uM)>) -> uM_h {
    var auc: uM_h = 0.0

    for i in 1..profile.len() {
        let (t1, c1) = profile[i-1]
        let (t2, c2) = profile[i]
        let dt: h = t2 - t1

        // Trapezoidal: (c1 + c2) / 2 × dt
        auc += (c1 + c2) / 2.0 * dt
    }

    auc
}

/// Find Cmax and Tmax
fn find_cmax(profile: &Vec<(h, uM)>) -> (uM, h) {
    var cmax: uM = 0.0
    var tmax: h = 0.0

    for (t, c) in profile {
        if c > cmax {
            cmax = c
            tmax = t
        }
    }

    (cmax, tmax)
}

// =============================================================================
// MAIN ENTRY POINT
// =============================================================================

fn main() -> effect[IO] {
    // $(drug_name) parameters
    let params = DrugParams {
        name: "$(drug_name)",
        MW: $(MW),
        ka: $(ka),
        F: $(F),
        Fg: $(F^0.5),   // Approximate
        Fh: $(F^0.5),   // Approximate
        Vc: $(Vc),
        Vp: $(Vp),
        CL: $(CL),
        Q: $(Q),
    }

    // Simulate single dose
    let dose: mg = 100.0
    let results = simulate(params, dose, 24.0, 0.1)

    // Calculate metrics
    let auc = calculate_auc(&results)
    let (cmax, tmax) = find_cmax(&results)

    // Print results
    println!("=== $(drug_name) PK Simulation ===")
    println!("Dose: {dose} mg")
    println!("AUC(0-24h): {auc:.1} µM·h")
    println!("Cmax: {cmax:.2} µM")
    println!("Tmax: {tmax:.1} h")

    // COMPILE-TIME TYPE SAFETY EXAMPLES:
    // These would cause compile errors:
    // let wrong: L = auc           // Error! uM_h != L
    // let wrong: mg = cmax         // Error! uM != mg
    // let wrong = auc + dose       // Error! Can't add uM_h + mg
}
"""
end

