"""
Abstract Syntax Tree node types for MedLang.
"""
abstract type MedLangNode end

struct MedLangModel <: MedLangNode
    name::String
    drug_name::String
    compartments::Vector{MedLangNode}
    parameters::Vector{MedLangNode}
    equations::Vector{MedLangNode}
    observables::Vector{MedLangNode}
end

struct MedLangParameter <: MedLangNode
    name::String
    value::Float64
    unit::String
    description::String
end

struct MedLangState <: MedLangNode
    name::String
    initial_value::Float64
    unit::String
end

struct MedLangODE <: MedLangNode
    state_name::String
    rhs::String  # Right-hand side expression
end

struct MedLangObservable <: MedLangNode
    name::String
    expression::String
    unit::String
end

struct MedLangDDI <: MedLangNode
    perpetrator::String
    victim::String
    mechanism::Symbol
    parameters::Dict{String, Float64}
end

