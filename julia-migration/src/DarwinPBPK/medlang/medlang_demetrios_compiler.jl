"""
Map MedLang units to Demetrios type-safe units.
Demetrios uses compile-time dimensional analysis.
"""
const UNIT_MAPPING = Dict{String, String}(
    # Concentrations
    "µM" => "uM",
    "μM" => "uM",
    "uM" => "uM",
    "nM" => "nM",
    "ng/mL" => "ng_per_mL",
    "mg/L" => "mg_per_L",
    "µg/mL" => "ug_per_mL",

    # Clearance
    "L/h" => "L_per_h",
    "mL/min" => "mL_per_min",
    "µL/min/mg" => "uL_per_min_per_mg",
    "mL/min/kg" => "mL_per_min_per_kg",

    # Volumes
    "L" => "L",
    "mL" => "mL",
    "L/kg" => "L_per_kg",

    # Mass
    "mg" => "mg",
    "kg" => "kg",
    "g" => "g",

    # Time
    "h" => "h",
    "min" => "min",
    "s" => "s",

    # Rate constants
    "1/h" => "per_h",
    "h⁻¹" => "per_h",
    "1/min" => "per_min",

    # Fractions (dimensionless)
    "" => "Real",
    "fraction" => "Real",
    "%" => "Percent",

    # Specialized PBPK units
    "pmol/min/mg" => "pmol_per_min_per_mg",
    "pmol/mg" => "pmol_per_mg",
)

"""
Demetrios unit type definitions (generated preamble).
"""
const DEMETRIOS_UNIT_TYPES = """
// =============================================================================
// DEMETRIOS UNIT TYPE DEFINITIONS FOR PBPK
// =============================================================================
// Compile-time dimensional analysis prevents unit errors
// Generated by Darwin PBPK Platform MedLang Compiler

// Base units
type mg = Mass<mg>
type g = Mass<g>
type kg = Mass<kg>
type L = Volume<L>
type mL = Volume<mL>
type h = Time<h>
type min = Time<min>
type s = Time<s>

// Concentration units
type uM = Amount<umol> / Volume<L>           // micromolar
type nM = Amount<nmol> / Volume<L>           // nanomolar
type ng_per_mL = Mass<ng> / Volume<mL>       // ng/mL
type mg_per_L = Mass<mg> / Volume<L>         // mg/L
type ug_per_mL = Mass<ug> / Volume<mL>       // µg/mL

// Clearance units
type L_per_h = Volume<L> / Time<h>           // L/h
type mL_per_min = Volume<mL> / Time<min>     // mL/min
type uL_per_min_per_mg = Volume<uL> / Time<min> / Mass<mg>  // intrinsic clearance
type mL_per_min_per_kg = Volume<mL> / Time<min> / Mass<kg>  // body weight normalized

// Volume distribution units
type L_per_kg = Volume<L> / Mass<kg>         // Vd normalized to body weight

// Rate constants
type per_h = 1 / Time<h>                     // h⁻¹
type per_min = 1 / Time<min>                 // min⁻¹

// Enzyme kinetics
type pmol_per_min_per_mg = Amount<pmol> / Time<min> / Mass<mg>  // Vmax
type pmol_per_mg = Amount<pmol> / Mass<mg>   // Enzyme abundance

// Fractions (dimensionless, but type-safe)
type Fraction = Real { 0.0 <= self <= 1.0 }  // Refinement type!
type Percent = Real { 0.0 <= self <= 100.0 }

// =============================================================================
// UNIT CONVERSION FUNCTIONS
// =============================================================================

/// Convert mL/min to L/h (common PBPK conversion)
fn mL_min_to_L_h(cl: mL_per_min) -> L_per_h {
    cl * 0.06  // mL/min × 60 min/h × 1 L/1000 mL = L/h × 0.06
}

/// Convert µL/min/mg to L/h (microsomal to whole liver)
fn CLint_to_CLh(
    clint: uL_per_min_per_mg,
    mppgl: pmol_per_mg,     // mg microsomal protein per g liver
    liver_weight: g         // liver weight
) -> L_per_h {
    clint * mppgl * liver_weight * 60.0 / 1_000_000.0
}

/// Convert µM to ng/mL given MW
fn uM_to_ng_mL(conc: uM, mw: g) -> ng_per_mL {
    conc * mw  // µM × g/mol = µg/L = ng/mL
}
"""

