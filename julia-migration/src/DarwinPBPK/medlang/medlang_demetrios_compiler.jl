"""
Container for generated Demetrios code.
"""
struct DemetriosCode
    preamble::String
    types::String
    parameters::String
    state::String
    functions::String
    effects::String
    main::String
end

"""
Convert MedLang unit string to Demetrios type.
"""
function medlang_unit_to_demetrios(unit::String)::String
    # Clean up the unit string
    unit_clean = strip(unit)

    # Direct mapping
    if haskey(UNIT_MAPPING, unit_clean)
        return UNIT_MAPPING[unit_clean]
    end

    # Try to construct compound unit
    # e.g., "mg/L" -> "mg_per_L"
    unit_demetrios = replace(unit_clean, "/" => "_per_")
    unit_demetrios = replace(unit_demetrios, " " => "_")
    unit_demetrios = replace(unit_demetrios, "µ" => "u")
    unit_demetrios = replace(unit_demetrios, "μ" => "u")
    unit_demetrios = replace(unit_demetrios, "⁻¹" => "")

    return unit_demetrios
end

"""
Generate Demetrios code for a PBPK model parameter.
"""
function generate_parameter(param::MedLangParameter)::String
    unit_type = medlang_unit_to_demetrios(param.unit)

    # Use refinement types for fractions
    if param.unit == "fraction" || (0.0 <= param.value <= 1.0 && param.unit == "")
        return """
    /// $(param.description)
    let $(param.name): Fraction = $(param.value)"""
    end

    return """
    /// $(param.description)
    let $(param.name): $(unit_type) = $(param.value)"""
end

"""
Generate Demetrios code for a state variable.
"""
function generate_state(state::MedLangState)::String
    unit_type = medlang_unit_to_demetrios(state.unit)

    return """
    /// State: $(state.name)
    var $(state.name): $(unit_type) = $(state.initial_value)"""
end

"""
Generate Demetrios ODE function.
"""
function generate_ode_function(equations::Vector{MedLangODE}, model_name::String)::String
    buf = IOBuffer()

    println(buf, """
/// ODE system for $(model_name)
/// Uses algebraic effects for safe mutation
fn ode_system(
    t: h,
    state: &mut PBPKState,
    params: &PBPKParams
) -> effect[Mut] {""")

    for eq in equations
        # Parse RHS and add type annotations
        rhs = eq.rhs
        println(buf, "    // d$(eq.state_name)/dt")
        println(buf, "    state.d_$(eq.state_name) = $(rhs)")
        println(buf)
    end

    println(buf, "}")

    return String(take!(buf))
end

"""
Generate Demetrios struct for PBPK parameters.
"""
function generate_params_struct(params::Vector{MedLangParameter})::String
    buf = IOBuffer()

    println(buf, """
/// PBPK model parameters with compile-time unit checking
struct PBPKParams {""")

    for param in params
        unit_type = medlang_unit_to_demetrios(param.unit)
        println(buf, "    $(param.name): $(unit_type),  // $(param.description)")
    end

    println(buf, "}")

    return String(take!(buf))
end

"""
Generate Demetrios struct for state variables.
"""
function generate_state_struct(states::Vector{MedLangState})::String
    buf = IOBuffer()

    println(buf, """
/// PBPK state variables (concentrations, amounts)
struct PBPKState {""")

    for state in states
        unit_type = medlang_unit_to_demetrios(state.unit)
        println(buf, "    $(state.name): $(unit_type),")
        println(buf, "    d_$(state.name): $(unit_type)_per_h,  // derivative")
    end

    println(buf, "}")

    return String(take!(buf))
end

