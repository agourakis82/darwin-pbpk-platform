# =============================================================================
# MEDLANG-TO-DEMETRIOS COMPILER
# =============================================================================
# Transpiles MedLang DSL (domain-specific PBPK language) to Demetrios
# (novel L0 systems + scientific programming language)
#
# KEY INNOVATION:
# Demetrios provides compile-time dimensional analysis (units of measure)
# which catches unit errors that are a major source of bugs in PBPK modeling.
#
# Example transformation:
#   MedLang: CLint: 125.0 µL/min/mg
#   Demetrios: let CLint: uL_per_min_per_mg = 125.0
#
# The Demetrios compiler will reject:
#   let result: L_per_h = CLint  // Type error! Wrong units
#
# This catches errors like:
# - Forgetting to convert µL/min to L/h
# - Using mg instead of kg for body weight
# - Mixing concentration units (µM vs ng/mL)
#
# Darwin PBPK Platform v2.10.0
# Author: Dr. Demetrios Agourakis
# Date: November 2025
# =============================================================================

module MedLangDemetriosCompiler

export compile_medlang_to_demetrios, MedLangAST, DemetriosCode
export generate_demetrios_pbpk, generate_demetrios_ddi

